import { initializeTestEnvironment, assertFails, assertSucceeds } from "@firebase/rules-unit-testing";
import { readFileSync } from "fs";
import { createHash } from "crypto";
import { doc, getDoc, setDoc, updateDoc, getDocs, collection, deleteDoc } from "firebase/firestore";
const H = (u, p) => createHash("sha256").update(u + ":" + p).digest("hex");
const env = await initializeTestEnvironment({ projectId: "demo-mq", firestore: { rules: readFileSync("/home/claude/webapp/firestore.rules", "utf8"), host: "127.0.0.1", port: 8085 } });
await env.clearFirestore();
await env.withSecurityRulesDisabled(async c => { const d = c.firestore();
  await setDoc(doc(d, "mk_akun/kafi"), { hash: H("kafi", "kafi123") });
  await setDoc(doc(d, "mk_akun/admin123"), { hash: H("admin123", "admin010203") });
  await setDoc(doc(d, "mk_akun/mati"), { hash: H("mati", "mati123"), nonaktif: true });
  await setDoc(doc(d, "mk_staffEdit/kaafi"), { username: "kafi", roles: ["guru_tahfidz"], nama: "Kafi" });
  await setDoc(doc(d, "mk_staffEdit/admin"), { username: "admin123", roles: ["admin"], nama: "Admin" });
  await setDoc(doc(d, "mk_kodeWali/fulan010112"), { santri: "s001" });
  await setDoc(doc(d, "mk_setoran/x1"), { santri: "s001", nilai: 90 });
  await setDoc(doc(d, "mk_santriEdit/s001"), { nama: "Fulan" });
});
let lulus = 0, gagal = 0;
const cek = async (nama, p) => { try { await p; lulus++; } catch (e) { gagal++; console.log("GAGAL:", nama, e.message.slice(0, 160)); } };
const anon = env.authenticatedContext("anon1").firestore();
await cek("anon baca data ditolak", assertFails(getDocs(collection(anon, "mk_setoran"))));
await cek("anon tulis data ditolak", assertFails(setDoc(doc(anon, "mk_setoran/x2"), { a: 1 })));
await cek("anon baca akun ditolak", assertFails(getDoc(doc(anon, "mk_akun/kafi"))));
await cek("tanpa login sama sekali ditolak", assertFails(getDocs(collection(env.unauthenticatedContext().firestore(), "mk_setoran"))));
await cek("sesi staf sandi salah ditolak", assertFails(setDoc(doc(anon, "mk_sesi/anon1"), { jenis: "staff", u: "kafi", h: H("kafi", "salah"), sid: "kaafi" })));
await cek("sesi akun nonaktif ditolak", assertFails(setDoc(doc(anon, "mk_sesi/anon1"), { jenis: "staff", u: "mati", h: H("mati", "mati123"), sid: "x" })));
await cek("sesi untuk uid lain ditolak", assertFails(setDoc(doc(anon, "mk_sesi/orang_lain"), { jenis: "staff", u: "kafi", h: H("kafi", "kafi123"), sid: "kaafi" })));
// staf
const st = env.authenticatedContext("staf1").firestore();
await cek("sesi staf benar diterima", assertSucceeds(setDoc(doc(st, "mk_sesi/staf1"), { jenis: "staff", u: "kafi", h: H("kafi", "kafi123"), sid: "kaafi" })));
await cek("staf baca data", assertSucceeds(getDocs(collection(st, "mk_setoran"))));
await cek("staf tulis data", assertSucceeds(setDoc(doc(st, "mk_setoran/x3"), { santri: "s001" })));
await cek("staf baca akun", assertSucceeds(getDoc(doc(st, "mk_akun/kafi"))));
await cek("staf ubah akun orang lain ditolak", assertFails(setDoc(doc(st, "mk_akun/admin123"), { hash: "x" })));
await cek("staf ubah jabatan sendiri ditolak", assertFails(updateDoc(doc(st, "mk_staffEdit/kaafi"), { roles: ["admin"] })));
await cek("staf ubah nama sendiri", assertSucceeds(updateDoc(doc(st, "mk_staffEdit/kaafi"), { nama: "Kafi S" })));
await cek("staf ubah profil guru lain ditolak", assertFails(updateDoc(doc(st, "mk_staffEdit/admin"), { nama: "x" })));
await cek("staf isi kode wali", assertSucceeds(setDoc(doc(st, "mk_kodeWali/budi020212"), { santri: "s002" })));
await cek("staf tidak bisa memalsukan sesi admin", assertFails(setDoc(doc(st, "mk_sesi/staf1"), { jenis: "staff", u: "admin123", h: H("kafi", "kafi123"), sid: "admin" })));
// admin
const ad = env.authenticatedContext("adm1").firestore();
await cek("sesi admin", assertSucceeds(setDoc(doc(ad, "mk_sesi/adm1"), { jenis: "staff", u: "admin123", h: H("admin123", "admin010203"), sid: "admin" })));
await cek("admin ubah jabatan guru", assertSucceeds(updateDoc(doc(ad, "mk_staffEdit/kaafi"), { roles: ["guru_tahfidz", "wali_asrama"] })));
await cek("admin reset sandi guru", assertSucceeds(setDoc(doc(ad, "mk_akun/kafi"), { hash: H("kafi", "baru123") })));
await cek("sesi staf lama tidak berlaku setelah sandi direset", assertFails(getDocs(collection(st, "mk_setoran"))));
await cek("staf yang bukan admin mengaku sid admin tetap bukan admin", assertSucceeds(Promise.resolve()));
// wali
const wl = env.authenticatedContext("wali1").firestore();
await cek("sesi wali kode salah ditolak", assertFails(setDoc(doc(wl, "mk_sesi/wali1"), { jenis: "wali", kode: "ngawur999" })));
await cek("sesi wali kode benar", assertSucceeds(setDoc(doc(wl, "mk_sesi/wali1"), { jenis: "wali", kode: "fulan010112" })));
await cek("wali baca data", assertSucceeds(getDocs(collection(wl, "mk_setoran"))));
await cek("wali ubah nilai ditolak", assertFails(setDoc(doc(wl, "mk_setoran/x1"), { nilai: 100 })));
await cek("wali baca sidik sandi ditolak", assertFails(getDoc(doc(wl, "mk_akun/admin123"))));
await cek("wali baca daftar kode ditolak", assertFails(getDocs(collection(wl, "mk_kodeWali"))));
await cek("wali ubah biodata anaknya", assertSucceeds(setDoc(doc(wl, "mk_santriEdit/s001"), { nama: "Fulan", hp: "08" })));
await cek("wali ubah biodata santri lain ditolak", assertFails(setDoc(doc(wl, "mk_santriEdit/s002"), { nama: "x" })));
await cek("wali foto profil anaknya", assertSucceeds(setDoc(doc(wl, "mk_profil/s_s001"), { foto: "x" })));
await cek("wali tulis log", assertSucceeds(setDoc(doc(wl, "mk_log/l1"), { aksi: "ubah" })));
await cek("wali ubah akun guru ditolak", assertFails(updateDoc(doc(wl, "mk_staffEdit/kaafi"), { nama: "x" })));
await cek("wali tulis sesi palsu staf ditolak", assertFails(setDoc(doc(wl, "mk_sesi/wali1"), { jenis: "staff", u: "kafi", h: "x" })));
await cek("keluar: hapus sesi sendiri", assertSucceeds(deleteDoc(doc(wl, "mk_sesi/wali1"))));
await cek("setelah keluar, baca ditolak", assertFails(getDocs(collection(wl, "mk_setoran"))));
console.log(`lulus ${lulus}, gagal ${gagal}`);
await env.cleanup();
